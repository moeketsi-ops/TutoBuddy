"""Builds seed/papers/grade_XX/<id>.json: past papers as clean questions,
marks and memo points, so Katlego can set a real paper and mark it against
the memo.

Converted by hand on 5 Nov 2026 from the OCR'd files in seed/past_papers
(question paper + official marking guideline). OCR garbles maths, so each
question was rebuilt from the paper AND its memo and the final answers were
re-worked (and SymPy-checked where computable, see tests/test_papers_unit.py).

STATUS: every paper is "unverified". Before learners see a paper, check
each question against the original PDF (fractions, signs, inequality
symbols and roots are where OCR fails). Questions that need a diagram or a
sketch, or whose text could not be recovered, are left out and listed in
"left_out" with the reason. Marks shown to learners are the marks of the
questions kept.

Copyright: these are provincial and district common tests, mostly
downloaded via third-party sites (source_site). Founder decision (10 Sep
2026): accept the risk while testing; get legal advice before live use.
See claude/content-sourcing-copyright-strategy.md.

check types (what code can verify in the learner's final answer):
  value      "value": a number                       e.g. 1/4
  solutions  "var", "values": every root, any order e.g. x = 3 or x = -2
  expression "expr": equivalent to this, in "form"    e.g. (5x + 3)(x - 1)
  point      "point": [x, y]                         e.g. (0; -2)
  none       the model marks it against the memo (proofs, intervals, words)
topic: the learner's own-grade CAPS topic the marks count towards, or None
(Grade 12 Paper 1 opens with Grade 11 algebra: marked, but no mastery
evidence, because of the grade rule).
memo points: {"m": marks, "p": what earns them, "a": true for the
answer mark(s) a correct final answer alone earns}.

Run: python -m seed.papers.build_papers
"""

