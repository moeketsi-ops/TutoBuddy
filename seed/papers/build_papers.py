def q(n, topic, marks, text, memo, check=None, answer=None, context=None):
    assert sum(p["m"] for p in memo) == marks, (n, marks, memo)
    return {"n": n, "topic": topic, "marks": marks, "text": text, "context": context,
            "memo": memo, "check": check, "answer": answer}


def m(marks, point, a=False):
    return {"m": marks, "p": point, **({"a": True} if a else {})}


